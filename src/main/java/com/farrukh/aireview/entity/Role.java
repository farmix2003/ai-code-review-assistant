package com.farrukh.aireview.entity;

/**
 * Enum representing the different user roles in the system.
 *
 * Roles:
 * - USER: Standard user with basic access to code review functionality
 * - ADMIN: Administrator with elevated privileges for system management
 */
public enum Role {
    // Standard user role with basic access
    USER,

    // Administrator role with elevated privileges
    ADMIN
}
